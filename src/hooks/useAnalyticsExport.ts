import { useCallback, useRef, useState } from 'react'
import type { jsPDF } from 'jspdf'
import { downloadCsv, toCsv } from '../utils/csv'
import type { AnalyticsRow } from '../utils/csv'
import type { KpiMetrics } from '../utils/analyticsKpis'
import { formatCurrency, formatPercentage } from '../utils/analyticsKpis'
import { formatDate, formatUsdc } from '../utils/format'
import { logger } from '../utils/logger'

type JsPDFInstance = InstanceType<typeof import('jspdf').default>
type JsPDFConstructor = typeof import('jspdf').default

export const ANALYTICS_EXPORT_ERROR = 'Failed to generate PDF. Please try again.'

export type UseAnalyticsExportOptions = {
  rows: AnalyticsRow[]
  kpis: KpiMetrics
  period: string
  customRangeActive: boolean
  customFrom: string
  customTo: string
}

const ACCENT = [0, 195, 137] as const

function drawReport(
  doc: JsPDFInstance,
  rows: AnalyticsRow[],
  kpis: KpiMetrics,
  rangeLabel: string,
  filenameLabel: string,
) {
  // Header bar
  doc.setFillColor(...ACCENT)
  doc.rect(0, 0, 210, 28, 'F')
  doc.setTextColor(255, 255, 255)
  doc.setFontSize(20)
  doc.setFont('helvetica', 'bold')
  doc.text('Disciplr Analytics Report', 14, 18)

  // Period & date
  doc.setFontSize(9)
  doc.setFont('helvetica', 'normal')
  doc.text(`Period: ${rangeLabel}   •   Generated: ${formatDate(new Date())}`, 14, 24)

  // Key metrics section
  doc.setTextColor(30, 45, 66)
  doc.setFontSize(13)
  doc.setFont('helvetica', 'bold')
  doc.text('Key Metrics', 14, 42)

  const metrics: [string, string][] = [
    ['Total Capital Locked', `${formatCurrency(kpis.totalCapital)} USDC`],
    ['Success Rate', formatPercentage(kpis.averageSuccessRate)],
    ['Total Milestones', `${kpis.totalMilestones}`],
    ['Period', rangeLabel],
    [
      'vs Previous Period (Capital)',
      kpis.capitalDelta !== 0
        ? `${kpis.capitalDelta > 0 ? '+' : ''}${formatCurrency(kpis.capitalDelta)}`
        : 'No prior data',
    ],
    [
      'vs Previous Period (Success)',
      kpis.successDelta !== 0
        ? `${kpis.successDelta > 0 ? '+' : ''}${formatPercentage(kpis.successDelta, 1)}`
        : 'No prior data',
    ],
  ]

  doc.setFontSize(10)
  metrics.forEach(([label, value], i) => {
    const col = i % 2 === 0 ? 14 : 110
    const row = 52 + Math.floor(i / 2) * 14
    doc.setFont('helvetica', 'normal')
    doc.setTextColor(100, 110, 130)
    doc.text(label, col, row)
    doc.setFont('helvetica', 'bold')
    doc.setTextColor(20, 20, 30)
    doc.text(value, col, row + 6)
  })

  // Divider
  doc.setDrawColor(...ACCENT)
  doc.setLineWidth(0.5)
  doc.line(14, 94, 196, 94)

  // Performance data table
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(13)
  doc.setTextColor(30, 45, 66)
  doc.text('Performance Data', 14, 106)

  // Table header
  doc.setFillColor(240, 250, 247)
  doc.rect(14, 112, 182, 9, 'F')
  doc.setFontSize(9)
  doc.setTextColor(0, 195, 137)
  doc.text('PERIOD', 17, 118)
  doc.text('SUCCESS %', 60, 118)
  doc.text('FAILED %', 100, 118)
  doc.text('CAPITAL (USDC)', 135, 118)
  doc.text('MILESTONES', 175, 118)

  // Table rows
  rows.forEach((row, i) => {
    const y = 128 + i * 10
    if (i % 2 === 0) {
      doc.setFillColor(249, 252, 251)
      doc.rect(14, y - 5, 182, 10, 'F')
    }
    doc.setFont('helvetica', 'normal')
    doc.setTextColor(30, 45, 66)
    doc.text(row.name, 17, y)
    doc.setTextColor(0, 155, 110)
    doc.text(`${row.success}%`, 60, y)
    doc.setTextColor(200, 60, 55)
    doc.text(`${row.failed}%`, 100, y)
    doc.setTextColor(30, 45, 66)
    doc.text(`$${formatUsdc(row.capital)}`, 135, y)
    doc.text(`${row.milestones}`, 175, y)
  })

  // Capital flow
  const tableEnd = 128 + rows.length * 10 + 10
  doc.setDrawColor(...ACCENT)
  doc.line(14, tableEnd, 196, tableEnd)

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(13)
  doc.setTextColor(30, 45, 66)
  doc.text('Capital Flow Summary', 14, tableEnd + 12)

  const flow: [string, string, readonly [number, number, number]][] = [
    ['Released to Success Destinations', '$8,750 USDC', [0, 155, 110] as const],
    ['Redirected on Failure', '$2,400 USDC', [200, 60, 55] as const],
    ['Platform Fee (1%)', '$124 USDC', [100, 110, 130] as const],
  ]

  flow.forEach(([label, value, color], i) => {
    const y = tableEnd + 24 + i * 12
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(10)
    doc.setTextColor(100, 110, 130)
    doc.text(label, 17, y)
    doc.setFont('helvetica', 'bold')
    doc.setTextColor(...color)
    doc.text(value, 150, y)
  })

  // Footer
  doc.setFillColor(245, 248, 250)
  doc.rect(0, 278, 210, 20, 'F')
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8)
  doc.setTextColor(150, 160, 175)
  doc.text('Generated by Disciplr — Accountability on Stellar', 14, 288)
  doc.text('Page 1 of 1', 185, 288)

  doc.save(`disciplr-report-${filenameLabel}.pdf`)
}

/**
 * CSV and lazy-PDF export for the Analytics page. `jspdf` is only touched by
 * `exportPdf()`, so the vendor-jspdf chunk is never requested until the user
 * asks for a report.
 */
export function useAnalyticsExport({
  rows,
  kpis,
  period,
  customRangeActive,
  customFrom,
  customTo,
}: UseAnalyticsExportOptions) {
  const jsPDFRef = useRef<JsPDFConstructor | null>(null)
  const pdfExportInFlight = useRef(false)
  const [isExportLoading, setIsExportLoading] = useState(false)
  const [exportError, setExportError] = useState<string | null>(null)

  const rangeLabel = customRangeActive ? `${customFrom} → ${customTo}` : period
  const fileLabel = customRangeActive ? `${customFrom}-to-${customTo}` : period

  const exportCsv = useCallback(() => {
    if (rows.length === 0) return
    downloadCsv(toCsv(rows, 'analytics'), `disciplr-analytics-${fileLabel}.csv`)
  }, [rows, fileLabel])

  const exportPdf = useCallback(async () => {
    // Guard against concurrent invocations: a second click while a PDF is
    // already being generated must be a no-op to avoid duplicate downloads
    // and interleaved state updates.
    if (pdfExportInFlight.current) return
    pdfExportInFlight.current = true
    setExportError(null)
    setIsExportLoading(true)
    try {
      if (!jsPDFRef.current) {
        const mod = await import('jspdf')
        jsPDFRef.current = mod?.default ?? (mod as unknown as JsPDFConstructor)
      }

      if (!jsPDFRef.current) {
        throw new Error('jsPDF module did not expose a constructor')
      }

      const JsPDF = jsPDFRef.current
      const doc: JsPDFInstance = new JsPDF()
      drawReport(doc, rows, kpis, rangeLabel, fileLabel)
    } catch (err) {
      logger.error('Failed to load or run jsPDF', err)
      setExportError(ANALYTICS_EXPORT_ERROR)
    } finally {
      pdfExportInFlight.current = false
      setIsExportLoading(false)
    }
  }, [rows, kpis, rangeLabel, fileLabel])

  return { exportCsv, exportPdf, isExportLoading, exportError }
}
